// [INPUT]: the Solco repo's frontend (`bun run build:mobile` → dist-mobile/mobile.html, one self-contained page).
// [OUTPUT]: src/generated/chat-page.ts — that page as one string constant (`CHAT_PAGE_HTML`) plus its sha256.
// [POS]: dev-infrastructure only — the one way the desktop Chat page enters this repo; never edit the output by hand.
// [PROTOCOL]: 变更时更新此头部，然后检查 CLAUDE.md
// Usage: pnpm sync:chat-page   (SOLCO_REPO overrides ../solco; SKIP_BUILD=1 reuses an existing dist-mobile)
//        pnpm check:chat-page  (--check: build, write nothing, exit 1 when the embedded page is stale)
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const repo = resolve(process.env.SOLCO_REPO ?? join(import.meta.dirname, '..', '..', 'solco'));
const frontend = join(repo, 'frontend');
if (process.env.SKIP_BUILD !== '1') {
  execFileSync('bun', ['run', 'build:mobile'], { cwd: frontend, stdio: 'inherit' });
}
const html = await readFile(join(frontend, 'dist-mobile', 'mobile.html'), 'utf8').catch(() => {
  console.error(`no built page at ${frontend}/dist-mobile/mobile.html — run \`bun run build:mobile\` in the solco frontend`);
  process.exit(1);
});
const sha = createHash('sha256').update(html).digest('hex');
const out = join(import.meta.dirname, '..', 'src', 'generated', 'chat-page.ts');
if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (!current.includes(`CHAT_PAGE_SHA256 = '${sha}'`)) {
    console.error('src/generated/chat-page.ts is stale — run `pnpm sync:chat-page`');
    process.exit(1);
  }
  console.log(`chat page in sync (sha256 ${sha.slice(0, 12)})`);
  process.exit(0);
}
await mkdir(join(out, '..'), { recursive: true });
await writeFile(
  out,
  `// Code generated by scripts/sync-chat-page.mjs from solco/frontend (build:mobile). DO NOT EDIT.\n` +
    `export const CHAT_PAGE_SHA256 = '${sha}';\n` +
    `export const CHAT_PAGE_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`wrote ${out} (${html.length} bytes, sha256 ${sha.slice(0, 12)})`);
